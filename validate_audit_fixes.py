def read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except FileNotFoundError:
        return ""

def file_exists(path: Path) -> bool:
    return path.exists()

def check(section: str, label: str, passed: bool, fix: str = ""):
    icon = PASS if passed else FAIL
    results.append((section, label, passed, fix))
    status = "PASS" if passed else "FAIL"
    print(f"  {icon}  [{section}] {label}")
    if not passed and fix:
        print(f"         {WARN} FIX: {fix}")

def check_contains(path: Path, pattern: str, flags=0) -> bool:
    content = read(path)
    if not content:
        return False
    if flags:
        return bool(re.search(pattern, content, flags))
    return pattern in content

def count_occurrences(path: Path, pattern: str, use_regex=False) -> int:
    content = read(path)
    if not content:
        return 0
    if use_regex:
        return len(re.findall(pattern, content))
    return content.count(pattern)

